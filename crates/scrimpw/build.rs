//! Embeds scrimpw.manifest into scrimpw.exe with Microsoft's linker, so no
//! resource compiler is needed. Only for the MSVC toolchain on Windows.

fn main() {
    println!("cargo:rerun-if-changed=scrimpw.manifest");
    let target_env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if target_os == "windows" && target_env == "msvc" {
        let manifest =
            std::path::Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default()).join("scrimpw.manifest");
        println!("cargo:rustc-link-arg-bins=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg-bins=/MANIFESTINPUT:{}", manifest.display());
    }
}
